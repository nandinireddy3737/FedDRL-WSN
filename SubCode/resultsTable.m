function T=resultsTable(R)
n=R.actualRounds;
Round=(1:n)';
T=table(Round,R.energyRound(:),R.energy(:),R.residualEnergy(:), ...
    R.alive(:),R.dead(:),R.delay(:),R.throughput(:),R.reliability(:), ...
    R.loadBalance(:),R.PDR(:),R.packetLoss(:),R.routingOverhead(:), ...
    R.stability(:),R.reward(:),R.loss(:),R.drift(:),R.numCH(:), ...
    R.actorLR(:),R.criticLR(:),R.ppoClip(:),R.intrinsicWeight(:), ...
    'VariableNames',{'Round','EnergyConsumedRound','CumulativeEnergyConsumed', ...
    'ResidualEnergy','AliveNodes','DeadNodes','EndToEndDelay','Throughput', ...
    'RoutingReliability','LoadBalance','PDR','PacketLoss','RoutingOverhead', ...
    'ClusterStability','GlobalReward','LocalLoss','DriftDetected','NumCH', ...
    'ActorLR','CriticLR','PPOClip','IntrinsicWeight'});
end
